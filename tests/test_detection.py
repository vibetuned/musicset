from musicset import ClassMap, Element, Glyph, PageAnnotation, detection_annotations


def _page(elements: list[Element], glyphs: list[Glyph] | None = None) -> PageAnnotation:
    return PageAnnotation(
        score="s",
        page=1,
        width=1000.0,
        height=1000.0,
        pixel_width=100.0,
        pixel_height=100.0,
        elements=elements,
        glyphs=glyphs or [],
    )


def test_element_kind_beats_modifier_classes():
    cmap = ClassMap(("autogenerated", "pgHead"), {})
    page = _page([Element("h", ("pgHead", "autogenerated"), (0, 0, 500, 100))])
    assert [a["class"] for a in detection_annotations(page, cmap, (100, 100))] == ["pgHead"]


def test_refined_class_beats_svg_class():
    cmap = ClassMap(("stem", "stem8"), {})
    page = _page([Element("s", ("stem",), (0, 0, 10, 300), refined=("stem8",))])
    assert detection_annotations(page, cmap, (100, 100))[0]["class"] == "stem8"


def test_boxes_scale_to_the_image_and_drop_slivers():
    cmap = ClassMap(("note",), {})
    page = _page(
        [
            Element("n1", ("note",), (100, 200, 300, 400)),
            Element("n2", ("note",), (100, 200, 102, 400)),  # 0.4 px wide at 200x200
        ]
    )
    anns = detection_annotations(page, cmap, (200, 200))
    assert anns == [{"class": "note", "bbox": [20.0, 40.0, 60.0, 80.0], "id": "n1"}]


def test_system_staff_needs_its_own_target_and_is_rounded():
    page = _page([Element("sys", ("system-staff",), (1.23456, 0, 500, 300), synthetic=True)])
    assert detection_annotations(page, ClassMap(("system",), {}), (100, 100)) == []
    anns = detection_annotations(page, ClassMap(("system-staff",), {}), (100, 100))
    assert anns == [{"class": "system-staff", "bbox": [0.12, 0.0, 50.0, 30.0], "id": "sys"}]


def test_accidental_inside_key_signature_becomes_key_accidental():
    cmap = ClassMap(("accidentalSharp", "keyAccidSharp"), {"E262": "accidentalSharp"})
    page = _page(
        [
            Element("k", ("keySig",), (0, 0, 100, 100)),
            Element("ka", ("keyAccid",), (0, 0, 100, 100), parent=0),
            Element("a", ("accid",), (200, 0, 300, 100)),
        ],
        [
            Glyph("E262", (0, 0, 100, 100), element=1, owner="ka"),
            Glyph("E262", (200, 0, 300, 100), element=2, owner="a"),
        ],
    )
    labels = [(a["class"], a["id"]) for a in detection_annotations(page, cmap, (100, 100))]
    assert labels == [("keyAccidSharp", "ka"), ("accidentalSharp", "a")]


def test_tiny_score_labels(tiny_page: PageAnnotation):
    cmap = ClassMap(
        ("keyAccidSharp", "accidentalSharp", "stem32", "barlineFinal", "noteheadBlack"),
        {"E262": "accidentalSharp", "E0A4": "noteheadBlack"},
    )
    labels = [a["class"] for a in detection_annotations(tiny_page, cmap, (2100, 2970))]
    assert sorted(labels) == sorted(
        ["keyAccidSharp", "accidentalSharp", "stem32", "barlineFinal", *["noteheadBlack"] * 8]
    )
