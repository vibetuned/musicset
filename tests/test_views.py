# -- label sets ---------------------------------------------------------------


def test_builtin_label_sets():
    assert builtin_names() == ("full", "lite", "lite-pruned")
    sizes = {name: len(LabelSet.load(name).classes.target_classes) for name in builtin_names()}
    assert sizes == {"full": 107, "lite": 99, "lite-pruned": 91}


def test_full_set_drops_page_furniture():
    full = LabelSet.load("full")
    for name in ("pgHead", "autogenerated"):
        assert name not in full.classes.target_classes
        assert all(name not in members for members in full.groups.values())
        assert all(name not in members for members in full.node_roles.values())


def test_label_set_from_directory(tmp_path):
    (tmp_path / "config.json").write_text('{"target_classes": ["note"]}')
    (tmp_path / "smufl_mapping.json").write_text("{}")
    labels = LabelSet.load(tmp_path)
    assert labels.classes.target_classes == ("note",)
    assert not labels.has_graph_roles
    with pytest.raises(FileNotFoundError):
        LabelSet.load(tmp_path / "missing")


# -- graph ----------------------------------------------------------------------


def test_page_sort_key_is_natural():
    names = ["s_page10.json", "s_page2.json.gz", "s_page1.json"]
    assert sorted(names, key=page_sort_key) == ["s_page1.json", "s_page2.json.gz", "s_page10.json"]


def test_shared_ids_become_linked_pseudo_nodes():
    pages = [
        [
            {"class": "a", "id": "x", "bbox": [0, 0, 1, 1]},
            {"class": "b", "id": "x", "bbox": [0, 0, 1, 1]},
        ]
    ]
    annotations, nodes, links = graph_nodes(pages)
    assert list(nodes) == ["x", "x_b_1"]
    assert links == [("x", "x_b_1", 1)]
    assert pages[0][1]["id"] == "x"  # the input is not modified
    assert annotations[1]["_page"] == 0


def test_tiny_score_graph(tiny_xml: str, tiny_page: PageAnnotation):
    lite = LabelSet.load("lite")
    mei = Engraving.load(tiny_xml, RenderOptions()).mei()
    anns = detection_annotations(tiny_page, lite.classes, (2100, 2970))
    edges = build_edges(mei, [anns], lite.node_roles)
    kinds = {k for _, _, k in edges}
    assert {1, 3} <= kinds
    # consecutive layer events are chained in order: 8 notes + 3 rests
    assert sum(k == 3 for _, _, k in edges) == 10
    record = graph_record(edges)
    assert record["num_nodes"] == len(set(record["node_ids"]))


