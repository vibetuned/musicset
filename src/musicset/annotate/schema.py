"""Canonical page annotation.

One :class:`PageAnnotation` holds everything that can be read off a rendered
page, independent of any model's label set:

* ``elements`` - every classed ``<g>`` of the engraving (notes, staves, beams,
  dynamics...) in document order, with its SVG classes plus the classes
  musicset derives from geometry (``barlineSingle``, ``beam16``, ``stem8``...),
  its full-ink box, its parent in the engraving tree and any ``data-*``
  attributes the renderer attached (pitch, duration...).
* ``glyphs`` - every SMuFL glyph drawn on the page, by codepoint, with the
  element that owns it.

Coordinates are in the page's SVG user units (``width`` x ``height``), not
pixels, so the same annotation serves any raster resolution: a view scales it
to the image it is paired with. Project-specific label sets live in
:mod:`musicset.views`.
"""

from __future__ import annotations

import gzip
import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from musicset.annotate.geometry import BBox

SCHEMA_VERSION = 1


@dataclass(slots=True)
class Element:
    id: str | None
    classes: tuple[str, ...]
    """SVG classes, element kind first (``("pgHead", "autogenerated")``)."""
    bbox: BBox | None
    refined: tuple[str, ...] = ()
    """Finer classes musicset derives from geometry (``barlineSingle``, ``stem8``...)."""
    parent: int | None = None
    """Index (in ``PageAnnotation.elements``) of the nearest enclosing element."""
    attrs: dict[str, str] = field(default_factory=dict)
    text: str | None = None
    synthetic: bool = False
    """True for boxes musicset synthesizes that have no SVG group of their own."""

    def to_dict(self) -> dict[str, Any]:
        d: dict[str, Any] = {"classes": list(self.classes)}
        if self.refined:
            d["refined"] = list(self.refined)
        if self.id is not None:
            d["id"] = self.id
        if self.bbox is not None:
            d["bbox"] = list(self.bbox)
        if self.parent is not None:
            d["parent"] = self.parent
        if self.attrs:
            d["attrs"] = self.attrs
        if self.text is not None:
            d["text"] = self.text
        if self.synthetic:
            d["synthetic"] = True
        return d

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> Element:
        bbox = d.get("bbox")
        return cls(
            id=d.get("id"),
            classes=tuple(d["classes"]),
            bbox=tuple(bbox) if bbox is not None else None,
            refined=tuple(d.get("refined", ())),
            parent=d.get("parent"),
            attrs=d.get("attrs", {}),
            text=d.get("text"),
            synthetic=d.get("synthetic", False),
        )


@dataclass(slots=True)
class Glyph:
    code: str
    """SMuFL codepoint, e.g. ``"E050"`` (the same in every SMuFL font)."""
    bbox: BBox | None
    element: int | None = None
    """Index of the nearest enclosing element."""
    owner: str | None = None
    """Id of the nearest identified ancestor: the musical object the glyph draws."""

    def to_dict(self) -> dict[str, Any]:
        d: dict[str, Any] = {"code": self.code}
        if self.bbox is not None:
            d["bbox"] = list(self.bbox)
        if self.element is not None:
            d["element"] = self.element
        if self.owner is not None:
            d["owner"] = self.owner
        return d

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> Glyph:
        bbox = d.get("bbox")
        return cls(
            code=d["code"],
            bbox=tuple(bbox) if bbox is not None else None,
            element=d.get("element"),
            owner=d.get("owner"),
        )


@dataclass(slots=True)
class PageAnnotation:
    score: str
    page: int
    width: float
    height: float
    """Page size in SVG user units; every bbox lives in this space."""
    pixel_width: float
    pixel_height: float
    """Nominal raster size of the page at scale 1."""
    elements: list[Element] = field(default_factory=list)
    glyphs: list[Glyph] = field(default_factory=list)
    meta: dict[str, Any] = field(default_factory=dict)

    def ancestors(self, index: int | None) -> list[Element]:
        """The element at ``index`` followed by its enclosing elements, innermost first."""
        chain = []
        while index is not None:
            el = self.elements[index]
            chain.append(el)
            index = el.parent
        return chain

    def ids(self) -> set[str]:
        """Every element id drawn on this page."""
        return {el.id for el in self.elements if el.id is not None and not el.synthetic}

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema": SCHEMA_VERSION,
            "score": self.score,
            "page": self.page,
            "width": self.width,
            "height": self.height,
            "pixel_width": self.pixel_width,
            "pixel_height": self.pixel_height,
            "meta": self.meta,
            "elements": [el.to_dict() for el in self.elements],
            "glyphs": [g.to_dict() for g in self.glyphs],
        }

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> PageAnnotation:
        if d.get("schema") != SCHEMA_VERSION:
            raise ValueError(f"unsupported page annotation schema: {d.get('schema')!r}")
        return cls(
            score=d["score"],
            page=d["page"],
            width=d["width"],
            height=d["height"],
            pixel_width=d["pixel_width"],
            pixel_height=d["pixel_height"],
            elements=[Element.from_dict(e) for e in d["elements"]],
            glyphs=[Glyph.from_dict(g) for g in d["glyphs"]],
            meta=d.get("meta", {}),
        )

    def save(self, path: Path) -> None:
        """Write as JSON; gzip-compressed when the name ends in ``.gz``."""
        data = json.dumps(self.to_dict(), separators=(",", ":")).encode("utf-8")
        path.write_bytes(gzip.compress(data, mtime=0) if path.suffix == ".gz" else data)

    @classmethod
    def load(cls, path: Path) -> PageAnnotation:
        data = path.read_bytes()
        if path.suffix == ".gz":
            data = gzip.decompress(data)
        return cls.from_dict(json.loads(data))
