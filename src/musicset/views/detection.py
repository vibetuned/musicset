"""Object-detection view: a label set applied to a canonical page.

The output is the kakigori annotation format::

    {"image": "x_page1.png", "width": W, "height": H,
     "annotations": [{"class": "noteheadBlack", "bbox": [x1, y1, x2, y2], "id": "..."}]}

with boxes in pixels of the paired image. Labels come from two sources, the
same way kakigori defined them: element classes (Verovio's plus musicset's
derived ones) and glyph codepoints through a SMuFL -> label map.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from musicset.annotate.geometry import BBox
from musicset.annotate.schema import Element, Glyph, PageAnnotation

# Boxes thinner than this (pixels) are invisible slivers
MIN_SIZE_PX = 0.5


@dataclass(frozen=True, slots=True)
class ClassMap:
    target_classes: tuple[str, ...]
    smufl: dict[str, str]
    """SMuFL codepoint -> label, e.g. ``{"E0A4": "noteheadBlack"}``."""

    @classmethod
    def from_files(cls, config: Path, smufl: Path) -> ClassMap:
        """Load kakigori-style ``config.json`` (``target_classes``) and ``smufl_mapping.json``."""
        targets = json.loads(config.read_text(encoding="utf-8"))["target_classes"]
        mapping = json.loads(smufl.read_text(encoding="utf-8"))
        return cls(tuple(targets), mapping)

    def fingerprint(self) -> str:
        payload = json.dumps([self.target_classes, sorted(self.smufl.items())])
        return hashlib.sha256(payload.encode()).hexdigest()[:16]

    def element_label(self, element: Element) -> str | None:
        """The target class of an element.

        Geometry-refined classes win, then SVG classes in order, so the element
        kind beats modifiers: ``pgHead autogenerated`` is always ``pgHead``.
        (kakigori picked from a set intersection, whose order changes with
        Python's per-process string hashing.)
        """
        targets = set(self.target_classes)
        return next((c for c in (*element.refined, *element.classes) if c in targets), None)


def _to_pixels(box: BBox, sx: float, sy: float, width: int, height: int) -> list[float] | None:
    x1 = max(0.0, min(float(width), box[0] * sx))
    y1 = max(0.0, min(float(height), box[1] * sy))
    x2 = max(0.0, min(float(width), box[2] * sx))
    y2 = max(0.0, min(float(height), box[3] * sy))
    if (x2 - x1) < MIN_SIZE_PX or (y2 - y1) < MIN_SIZE_PX:
        return None
    return [x1, y1, x2, y2]


def _in_key_signature(page: PageAnnotation, glyph: Glyph) -> bool:
    return any(
        "keySig" in el.classes or "keyAccid" in el.classes for el in page.ancestors(glyph.element)
    )


# Elements that are events: a glyph drawn inside one belongs to it
_EVENTS = frozenset(("note", "chord", "rest", "mRest", "space"))
_CONTAINERS = frozenset(("layer", "staff", "measure", "system", "beam", "tuplet"))


def _event_parent(page: PageAnnotation, el) -> str | None:
    """Id of the note, chord or rest an element is drawn inside (its dots,
    accidental, articulation...), from the SVG nesting."""
    j = el.parent
    while j is not None:
        parent = page.elements[j]
        if _EVENTS.intersection(parent.classes) and parent.id is not None:
            return parent.id
        if _CONTAINERS.intersection(parent.classes):
            return None
        j = parent.parent
    return None


def detection_annotations(
    page: PageAnnotation, class_map: ClassMap, image_size: tuple[int, int]
) -> list[dict[str, Any]]:
    """Detection boxes in kakigori's format: ``class``, ``bbox`` (pixels),
    ``id``, plus ``parent`` (the owning event's id) on elements drawn inside
    a note, chord or rest; the graph view attaches those by it."""
    width, height = image_size
    sx, sy = width / page.width, height / page.height
    targets = set(class_map.target_classes)
    out: list[dict[str, Any]] = []

    for el in page.elements:
        if el.bbox is None:
            continue
        if el.synthetic:
            if "system-staff" not in targets:
                continue
            box = _to_pixels(el.bbox, sx, sy, width, height)
            if box is None:
                continue
            ann: dict[str, Any] = {"class": "system-staff", "bbox": [round(v, 2) for v in box]}
        else:
            label = class_map.element_label(el)
            if label is None:
                continue
            box = _to_pixels(el.bbox, sx, sy, width, height)
            if box is None:
                continue
            ann = {"class": label, "bbox": box}
        if el.id is not None:
            ann["id"] = el.id
        if not _EVENTS.intersection(el.classes) and (owner := _event_parent(page, el)):
            ann["parent"] = owner
        out.append(ann)

    for glyph in page.glyphs:
        label = class_map.smufl.get(glyph.code)
        if not label or glyph.bbox is None:
            continue
        # An accidental drawn inside a key signature is a key accidental
        if label.startswith("accidental") and _in_key_signature(page, glyph):
            label = label.replace("accidental", "keyAccid")
        if label not in targets:
            continue
        box = _to_pixels(glyph.bbox, sx, sy, width, height)
        if box is None:
            continue
        ann = {"class": label, "bbox": box}
        if glyph.owner is not None:
            ann["id"] = glyph.owner
        out.append(ann)

    return out


def detection_record(
    page: PageAnnotation, class_map: ClassMap, image_name: str, image_size: tuple[int, int]
) -> dict[str, Any]:
    """A full kakigori annotation file for one page image."""
    return {
        "image": image_name,
        "width": image_size[0],
        "height": image_size[1],
        "annotations": detection_annotations(page, class_map, image_size),
    }
