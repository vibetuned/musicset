"""Label sets: which classes a dataset annotates and how they relate.

A label set is a directory in kakigori's conf format::

    config.json         {"target_classes": [...]}   order = class index
    smufl_mapping.json  {"E0A4": "noteheadBlack"}    glyph codepoint -> class
    hierarchy.json      {"group": [classes]}         viewers, per-group metrics
    structure.json      {"node_roles": {...}}        graph groundtruth roles

Built-in sets (``musicset/labels/<name>/``): ``full`` (107 classes, kakigori's
full set without the ``pgHead``/``autogenerated`` page furniture), ``lite`` (99)
and ``lite-pruned`` (91). Any other directory in this format works too.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from importlib.resources import files
from pathlib import Path

from musicset.views.detection import ClassMap

_BUILTIN = Path(str(files(__package__)))


def builtin_names() -> tuple[str, ...]:
    return tuple(sorted(p.name for p in _BUILTIN.iterdir() if (p / "config.json").exists()))


@dataclass(frozen=True, slots=True)
class LabelSet:
    name: str
    classes: ClassMap
    groups: dict[str, list[str]]
    node_roles: dict[str, list[str]]

    @classmethod
    def load(cls, spec: str | Path) -> LabelSet:
        """A built-in set by name, or a directory in the conf format."""
        directory = _BUILTIN / str(spec) if str(spec) in builtin_names() else Path(spec)
        if not (directory / "config.json").exists():
            raise FileNotFoundError(
                f"{spec!r} is neither a built-in label set {builtin_names()} "
                "nor a directory with config.json"
            )

        def read(name: str) -> dict:
            path = directory / name
            return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}

        classes = ClassMap.from_files(directory / "config.json", directory / "smufl_mapping.json")
        return cls(
            name=directory.name,
            classes=classes,
            groups=read("hierarchy.json"),
            node_roles=read("structure.json").get("node_roles", {}),
        )

    @property
    def has_graph_roles(self) -> bool:
        return bool(self.node_roles)

    def fingerprint(self) -> str:
        payload = json.dumps([self.classes.fingerprint(), self.node_roles], sort_keys=True)
        return hashlib.sha256(payload.encode()).hexdigest()[:16]
